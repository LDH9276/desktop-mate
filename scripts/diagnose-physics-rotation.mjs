import vm from 'node:vm';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { Bone, BufferGeometry, Skeleton, SkinnedMesh, Quaternion, Vector3 } from 'three';
import { MMDPhysics } from '../src/vendor/MMDPhysics.js';
const context=vm.createContext({WebAssembly,console,TextDecoder,setTimeout,clearTimeout});
vm.runInContext(readFileSync('public/physics/ammo.wasm.js','utf8'),context);
globalThis.Ammo=await context.Ammo({wasmBinary:readFileSync('public/physics/ammo.wasm.wasm')});
const mesh=new SkinnedMesh(new BufferGeometry()),parent=new Bone(),child=new Bone();
mesh.add(parent);parent.add(child);child.position.y=1;mesh.bind(new Skeleton([parent,child]));
const physics=new MMDPhysics(mesh,[{boneIndex:1,type:1,shapeType:0,width:.1,height:0,depth:0,position:[0,0,0],rotation:[0,0,0],weight:1,positionDamping:.9,rotationDamping:.9,friction:0,restitution:0,groupIndex:1,groupTarget:0}],[],{gravity:new Vector3()});
parent.rotation.set(.4,.5,-.2);child.rotation.set(-.3,.2,.6);mesh.updateMatrixWorld(true);physics.reset();
const expected=child.getWorldQuaternion(new Quaternion());
parent.rotation.set(-.2,.8,.4);mesh.updateMatrixWorld(true);
physics.update(1/65);
const worldRotationError=expected.angleTo(child.getWorldQuaternion(new Quaternion()));
assert.ok(worldRotationError<1e-5,'parent rotation must not twist the simulated child');
console.log(JSON.stringify({result:'passed',worldRotationError}));
physics.dispose();
